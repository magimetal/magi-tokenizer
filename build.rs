// Builds the static lookup tables of each enabled encoding from its `assets/<name>.tiktoken` vocabulary, so the
// library starts with no parsing, hashing or allocation. Outputs land in OUT_DIR: raw little/big-endian table
// images plus `<name>_tables.rs`, which `src/tables.rs` includes.

use std::collections::HashMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs};

#[path = "src/table_hash.rs"]
#[allow(dead_code)]
mod table_hash;
use table_hash::*;

/// A vocabulary to build: name, enabling Cargo feature (None = always built), expected ordinary token and merge
/// pair counts. Token ids must fit the 18-bit pair-table field.
const VOCABULARIES: [(&str, Option<&str>, usize, usize); 2] = [
    ("o200k_base", None, 199_998, 446_189),
    ("cl100k_base", Some("CL100K_BASE"), 100_256, 233_378),
];
/// `PREMERGED_CHAR_TOKENS` has one entry per code point below this: every 2- and 3-byte UTF-8 character.
const PREMERGED_CHAR_COUNT: usize = 0x10000;

fn main() {
    println!("cargo:rerun-if-changed=src/table_hash.rs");
    println!("cargo:rerun-if-changed=build.rs");
    let little_endian = env::var("CARGO_CFG_TARGET_ENDIAN").expect("CARGO_CFG_TARGET_ENDIAN") == "little";
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR"));
    for (name, feature, expected_token_count, expected_pair_count) in VOCABULARIES {
        if feature.is_none_or(|feature| env::var_os(format!("CARGO_FEATURE_{feature}")).is_some()) {
            build_vocabulary(name, expected_token_count, expected_pair_count, little_endian, &out_dir);
        }
    }
}

fn build_vocabulary(
    name: &str,
    expected_token_count: usize,
    expected_pair_count: usize,
    little_endian: bool,
    out_dir: &Path,
) {
    let vocabulary_path = format!("assets/{name}.tiktoken");
    println!("cargo:rerun-if-changed={vocabulary_path}");
    let vocabulary = fs::read_to_string(&vocabulary_path).expect("read vocabulary");
    let tokens = parse_tiktoken_vocabulary(&vocabulary);
    assert_eq!(tokens.len(), expected_token_count, "unexpected {name} vocabulary size");
    assert!(tokens.len() < 1 << PAIR_ID_BITS);

    let mut id_by_bytes: HashMap<&[u8], u32> = HashMap::with_capacity(tokens.len());
    for (id, bytes) in tokens.iter().enumerate() {
        assert!(!bytes.is_empty() && bytes.len() <= MAX_TOKEN_BYTES, "token {id} has length {}", bytes.len());
        assert!(id_by_bytes.insert(bytes, id as u32).is_none(), "token {id} duplicates another token");
    }

    let mut token_bytes = Vec::new();
    let mut token_offsets = Vec::with_capacity(tokens.len() + 1);
    for bytes in &tokens {
        token_offsets.push(token_bytes.len() as u32);
        token_bytes.extend_from_slice(bytes);
    }
    token_offsets.push(token_bytes.len() as u32);

    // Library probe loops end at an empty slot, so each table keeps at least half its slots empty.
    let vocab_table_bits = table_bits_for(tokens.len());
    let pair_table_bits = table_bits_for(expected_pair_count);
    let vocab_table = build_vocab_table(&tokens, vocab_table_bits);
    let (pair_table, pair_count) = build_pair_table(&tokens, &id_by_bytes, pair_table_bits);
    assert_eq!(pair_count, expected_pair_count, "unexpected {name} merge pair count");

    let byte_tokens: Vec<u32> = (0..=255u8).map(|byte| id_by_bytes[&[byte][..]]).collect();
    let byte_pair_ranks: Vec<u32> = (0..65536u32)
        .map(|pair| *id_by_bytes.get(&[(pair >> 8) as u8, pair as u8][..]).unwrap_or(&u32::MAX))
        .collect();
    let premerged_char_tokens = build_premerged_char_tokens(&tokens, &id_by_bytes);
    let continuation_lead_ranks = build_continuation_lead_ranks(&tokens);

    let file = |table: &str| format!("{name}_{table}.bin");
    fs::write(out_dir.join(file("token_bytes")), &token_bytes).expect("write token bytes");
    write_words(&out_dir.join(file("token_offsets")), &token_offsets, little_endian);
    write_words(&out_dir.join(file("vocab_table")), &vocab_table, little_endian);
    write_words(&out_dir.join(file("pair_table")), &pair_table, little_endian);
    write_words(&out_dir.join(file("byte_pair_ranks")), &byte_pair_ranks, little_endian);
    write_words(&out_dir.join(file("premerged_char_tokens")), &premerged_char_tokens, little_endian);
    write_words(&out_dir.join(file("continuation_lead_ranks")), &continuation_lead_ranks, little_endian);

    let mut source = String::new();
    writeln!(source, "// @generated by build.rs from {vocabulary_path}. Do not edit.").unwrap();
    writeln!(source, "pub(crate) const TOKEN_COUNT: usize = {};", tokens.len()).unwrap();
    writeln!(source, "pub(crate) const TOKEN_BYTES_LEN: usize = {};", token_bytes.len()).unwrap();
    writeln!(source, "pub(crate) const VOCAB_TABLE_BITS: u32 = {vocab_table_bits};").unwrap();
    writeln!(source, "pub(crate) const PAIR_TABLE_BITS: u32 = {pair_table_bits};").unwrap();
    writeln!(source, "pub(crate) static BYTE_TOKENS: [u32; 256] = {byte_tokens:?};").unwrap();
    for (static_name, table, element, count) in [
        ("TOKEN_OFFSETS", "token_offsets", "u32", tokens.len() + 1),
        ("VOCAB_TABLE", "vocab_table", "u64", vocab_table.len()),
        ("PAIR_TABLE", "pair_table", "u64", pair_table.len()),
        ("BYTE_PAIR_RANKS", "byte_pair_ranks", "u32", byte_pair_ranks.len()),
        ("PREMERGED_CHAR_TOKENS", "premerged_char_tokens", "u32", premerged_char_tokens.len()),
        ("CONTINUATION_LEAD_RANKS", "continuation_lead_ranks", "u32", continuation_lead_ranks.len()),
    ] {
        writeln!(
            source,
            "pub(crate) static {static_name}: &[{element}] = {{\n    \
             static RAW: Aligned<[u8; {count} * size_of::<{element}>()]> = \
             Aligned(*include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{}\")));\n    \
             // SAFETY: RAW is 64-byte aligned, exactly {count} {element}s long, written in target byte order.\n    \
             unsafe {{ core::slice::from_raw_parts(RAW.0.as_ptr().cast::<{element}>(), {count}) }}\n}};",
            file(table)
        )
        .unwrap();
    }
    writeln!(
        source,
        "pub(crate) static TOKEN_BYTES: &[u8; TOKEN_BYTES_LEN] = include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{}\"));",
        file("token_bytes")
    )
    .unwrap();
    fs::write(out_dir.join(format!("{name}_tables.rs")), source).expect("write tables source");
}

/// Slot count exponent of a hash table holding `entries`: the smallest power of two at least twice as large.
fn table_bits_for(entries: usize) -> u32 {
    (2 * entries).next_power_of_two().trailing_zeros()
}

fn parse_tiktoken_vocabulary(text: &str) -> Vec<Vec<u8>> {
    let mut by_rank: Vec<Option<Vec<u8>>> = Vec::new();
    for line in text.lines().filter(|line| !line.is_empty()) {
        let (encoded, rank) = line.split_once(' ').expect("vocabulary line is `<base64> <rank>`");
        let rank: usize = rank.trim().parse().expect("vocabulary rank");
        if by_rank.len() <= rank {
            by_rank.resize(rank + 1, None);
        }
        assert!(by_rank[rank].replace(decode_base64(encoded)).is_none(), "duplicate rank {rank}");
    }
    by_rank
        .into_iter()
        .enumerate()
        .map(|(rank, bytes)| bytes.unwrap_or_else(|| panic!("missing rank {rank}")))
        .collect()
}

fn decode_base64(text: &str) -> Vec<u8> {
    let mut out = Vec::with_capacity(text.len() / 4 * 3);
    let (mut accumulator, mut bits) = (0u32, 0u32);
    for &c in text.as_bytes() {
        let value = match c {
            b'A'..=b'Z' => c - b'A',
            b'a'..=b'z' => c - b'a' + 26,
            b'0'..=b'9' => c - b'0' + 52,
            b'+' => 62,
            b'/' => 63,
            b'=' => break,
            _ => panic!("invalid base64 byte {c:#04x} in {text:?}"),
        };
        accumulator = accumulator << 6 | u32::from(value);
        bits += 6;
        if bits >= 8 {
            bits -= 8;
            out.push((accumulator >> bits) as u8);
            accumulator &= (1 << bits) - 1;
        }
    }
    out
}

/// Head (bytes 0..8) and tail (bytes 8..12) of a token as little-endian integers, zero padded.
fn inline_key(bytes: &[u8]) -> (u64, u32) {
    let mut head = [0u8; 8];
    let mut tail = [0u8; 4];
    for (i, &byte) in bytes.iter().take(INLINE_TOKEN_BYTES).enumerate() {
        if i < 8 { head[i] = byte } else { tail[i - 8] = byte }
    }
    (u64::from_le_bytes(head), u32::from_le_bytes(tail))
}

fn build_vocab_table(tokens: &[Vec<u8>], table_bits: u32) -> Vec<u64> {
    let mask = (1usize << table_bits) - 1;
    let mut table = vec![0u64; 2 << table_bits];
    for (id, bytes) in tokens.iter().enumerate() {
        let (head, tail) = inline_key(bytes);
        let mut slot = vocab_slot_for(head, tail, bytes.len(), table_bits);
        while table[2 * slot + 1] != 0 {
            slot = (slot + 1) & mask;
        }
        table[2 * slot] = head;
        table[2 * slot + 1] =
            u64::from(tail) | (id as u64) << VOCAB_SLOT_ID_SHIFT | (bytes.len() as u64) << VOCAB_SLOT_LEN_SHIFT;
    }
    table
}

/// Every split of a token into two tokens is a merge whose priority is the merged token's id.
fn build_pair_table(tokens: &[Vec<u8>], id_by_bytes: &HashMap<&[u8], u32>, table_bits: u32) -> (Vec<u64>, usize) {
    let mask = (1usize << table_bits) - 1;
    let mut table = vec![PAIR_EMPTY_SLOT; 1 << table_bits];
    let mut count = 0;
    for (id, bytes) in tokens.iter().enumerate() {
        for split in 1..bytes.len() {
            let (Some(&left), Some(&right)) = (id_by_bytes.get(&bytes[..split]), id_by_bytes.get(&bytes[split..]))
            else {
                continue;
            };
            let key = pair_key(left, right);
            let mut slot = pair_slot_for(key, table_bits);
            while table[slot] != PAIR_EMPTY_SLOT {
                assert_ne!(table[slot] >> PAIR_ID_BITS, key, "pair ({left}, {right}) merges twice");
                slot = (slot + 1) & mask;
            }
            table[slot] = key << PAIR_ID_BITS | id as u64;
            count += 1;
        }
    }
    (table, count)
}

/// For each code point below PREMERGED_CHAR_COUNT, the token of its 2- or 3-byte character if merging may start
/// with the character as one part, else 0 (token 0 is `!`, never such a character). That is exact when the
/// character's bytes merge on their own into its token, and every token joining some or all of the character to a
/// neighbor ranks above each of those merges: while the character is incomplete it always has a lower-ranked
/// merge pending, so no joining merge can come first, and starting it complete changes no other merge's order.
/// Neighbors are limited to what `premerged_char` checks: the byte before is a continuation byte, the byte after
/// starts a multibyte sequence, or the slice ends there.
///
/// Tokens joining only the last byte to the next character are left out: `premerged_char` checks them against
/// the actual next byte with `CONTINUATION_LEAD_RANKS`. Checking them here against every possible next character
/// made most CJK characters ineligible (#14). The last merge forms the token, so the highest merge is the token
/// itself, which the runtime check compares against.
fn build_premerged_char_tokens(tokens: &[Vec<u8>], id_by_bytes: &HashMap<&[u8], u32>) -> Vec<u32> {
    // Lowest token that is more bytes ending in a continuation byte, then the key; or the key, then more bytes
    // starting a multibyte sequence. Keys are at most 3 bytes, the longest character in the table.
    let mut lowest_joining_left: HashMap<&[u8], u32> = HashMap::new();
    let mut lowest_joining_right: HashMap<&[u8], u32> = HashMap::new();
    for (id, bytes) in tokens.iter().enumerate() {
        for split in 1..bytes.len() {
            if bytes.len() - split <= 3 && is_continuation_byte(bytes[split - 1]) {
                let lowest = lowest_joining_left.entry(&bytes[split..]).or_insert(u32::MAX);
                *lowest = (*lowest).min(id as u32);
            }
            if split <= 3 && starts_multibyte_sequence(bytes[split]) {
                let lowest = lowest_joining_right.entry(&bytes[..split]).or_insert(u32::MAX);
                *lowest = (*lowest).min(id as u32);
            }
        }
    }
    (0..PREMERGED_CHAR_COUNT as u32)
        .map(|code_point| {
            let Some(character) = char::from_u32(code_point).filter(|character| character.len_utf8() > 1) else {
                return 0;
            };
            let mut buffer = [0; 4];
            let bytes = character.encode_utf8(&mut buffer).as_bytes();
            let (Some(&id), Some(highest_inner_merge)) =
                (id_by_bytes.get(bytes), highest_merge_of_lone_token(bytes, id_by_bytes))
            else {
                return 0;
            };
            assert_eq!(highest_inner_merge, id, "{character:?} has a merge ranked above its own token");
            let joining_left = (1..=bytes.len()).filter_map(|end| lowest_joining_left.get(&bytes[..end]));
            let joining_right = (0..bytes.len() - 1).filter_map(|start| lowest_joining_right.get(&bytes[start..]));
            let lowest_joining = joining_left.chain(joining_right).copied().min().unwrap_or(u32::MAX);
            assert_ne!(id, 0);
            if lowest_joining > highest_inner_merge { id } else { 0 }
        })
        .collect()
}

/// Lowest token starting with a continuation byte then a byte that starts a multibyte sequence, indexed by
/// `(continuation & 0x3F) << 6 | (lead & 0x3F)`; u32::MAX when there is none.
fn build_continuation_lead_ranks(tokens: &[Vec<u8>]) -> Vec<u32> {
    let mut ranks = vec![u32::MAX; 1 << 12];
    for (id, bytes) in tokens.iter().enumerate() {
        if let [continuation, lead, ..] = bytes[..]
            && is_continuation_byte(continuation)
            && starts_multibyte_sequence(lead)
        {
            let rank = &mut ranks[((continuation & 0x3F) as usize) << 6 | (lead & 0x3F) as usize];
            *rank = (*rank).min(id as u32);
        }
    }
    ranks
}

/// Highest rank among the merges of `bytes` on their own, if they end as one token.
fn highest_merge_of_lone_token(bytes: &[u8], id_by_bytes: &HashMap<&[u8], u32>) -> Option<u32> {
    let mut parts: Vec<Vec<u8>> = bytes.iter().map(|&byte| vec![byte]).collect();
    let mut highest = 0;
    while parts.len() > 1 {
        let (rank, left) = (0..parts.len() - 1)
            .filter_map(|left| Some((*id_by_bytes.get(&[&parts[left][..], &parts[left + 1]].concat()[..])?, left)))
            .min()?;
        highest = highest.max(rank);
        let right = parts.remove(left + 1);
        parts[left].extend(right);
    }
    Some(highest)
}

trait TableWord: Copy {
    fn to_bytes(self, little_endian: bool, out: &mut Vec<u8>);
}
impl TableWord for u32 {
    fn to_bytes(self, little_endian: bool, out: &mut Vec<u8>) {
        out.extend_from_slice(&if little_endian { self.to_le_bytes() } else { self.to_be_bytes() });
    }
}
impl TableWord for u64 {
    fn to_bytes(self, little_endian: bool, out: &mut Vec<u8>) {
        out.extend_from_slice(&if little_endian { self.to_le_bytes() } else { self.to_be_bytes() });
    }
}

fn write_words<T: TableWord>(path: &Path, words: &[T], little_endian: bool) {
    let mut bytes = Vec::with_capacity(size_of_val(words));
    words.iter().for_each(|word| word.to_bytes(little_endian, &mut bytes));
    fs::write(path, bytes).unwrap_or_else(|error| panic!("write {}: {error}", path.display()));
}

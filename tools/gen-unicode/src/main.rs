//! Generates `src/unicode_classes.rs`: one class byte per code point for the o200k scanner.
//!
//! Every class is computed by the same `regex` / `regex-syntax` versions that tiktoken-rs
//! uses, so the scanner sees exactly the reference regex's Unicode semantics.

use regex::Regex;
use std::{collections::HashMap, fmt::Write, fs, path::Path};

const BASE_PUNCT: u8 = 0;
const BASE_LETTER: u8 = 1;
const BASE_NUMBER: u8 = 2;
const BASE_SPACE: u8 = 3;
const BASE_NEWLINE: u8 = 4;
const UPPER: u8 = 0x08;
const LOWER: u8 = 0x10;

fn whole(pattern: &str) -> Regex {
    Regex::new(&format!(r"\A(?:{pattern})\z")).unwrap()
}

fn main() {
    let letter = whole(r"\p{L}");
    let number = whole(r"\p{N}");
    let space = whole(r"\s");
    let upper = whole(r"[\p{Lu}\p{Lt}\p{Lm}\p{Lo}\p{M}]");
    let lower = whole(r"[\p{Ll}\p{Lm}\p{Lo}\p{M}]");

    // Contraction letters: the scanner compares ASCII bytes and special-cases U+017F only.
    for ascii in ['s', 't', 'r', 'e', 'v', 'm', 'l', 'd'] {
        let folded = whole(&format!("(?i:{ascii})"));
        let extra: Vec<char> = (0..=0x10FFFFu32)
            .filter_map(char::from_u32)
            .filter(|c| !c.eq_ignore_ascii_case(&ascii) && folded.is_match(c.encode_utf8(&mut [0; 4])))
            .collect();
        let expected: &[char] = if ascii == 's' { &['\u{17F}'] } else { &[] };
        assert_eq!(extra, expected, "unexpected case folds for {ascii}");
    }

    let mut classes = vec![0u8; 0x110000];
    for (code, class) in classes.iter_mut().enumerate() {
        let Some(c) = char::from_u32(code as u32) else { continue };
        let text = c.encode_utf8(&mut [0; 4]).to_owned();
        let flags = [letter.is_match(&text), number.is_match(&text), space.is_match(&text)];
        assert!(flags.iter().filter(|&&f| f).count() <= 1, "overlapping base classes at {code:#x}");
        let mut value = match flags {
            [true, _, _] => BASE_LETTER,
            [_, true, _] => BASE_NUMBER,
            [_, _, true] if c == '\r' || c == '\n' => BASE_NEWLINE,
            [_, _, true] => BASE_SPACE,
            _ => BASE_PUNCT,
        };
        if upper.is_match(&text) {
            value |= UPPER;
        }
        if lower.is_match(&text) {
            value |= LOWER;
        }
        assert!(value & 7 != BASE_LETTER || value & (UPPER | LOWER) != 0, "letter without case group at {code:#x}");
        *class = value;
    }

    let mut block_index: HashMap<&[u8], usize> = HashMap::new();
    let mut blocks: Vec<&[u8]> = Vec::new();
    let mut stage1 = Vec::new();
    for block in classes.chunks(256) {
        let next = blocks.len();
        let index = *block_index.entry(block).or_insert_with(|| {
            blocks.push(block);
            next
        });
        stage1.push(index);
    }
    assert!(blocks.len() <= 256, "stage1 no longer fits in u8");

    let mut out = String::new();
    writeln!(out, "// @generated by tools/gen-unicode from regex-syntax 0.8.11 (Unicode 16.0.0). Do not edit.").unwrap();
    writeln!(out, "// Class byte: bits 0-2 base (0 punct, 1 letter, 2 number, 3 space, 4 newline),").unwrap();
    writeln!(out, "// 0x08 = [\\p{{Lu}}\\p{{Lt}}\\p{{Lm}}\\p{{Lo}}\\p{{M}}], 0x10 = [\\p{{Ll}}\\p{{Lm}}\\p{{Lo}}\\p{{M}}].").unwrap();
    let mut emit = |name: &str, values: &mut dyn Iterator<Item = usize>, len: usize| {
        writeln!(out, "pub(crate) static {name}: [u8; {len}] = [").unwrap();
        let values: Vec<usize> = values.collect();
        for row in values.chunks(32) {
            let line: Vec<String> = row.iter().map(usize::to_string).collect();
            writeln!(out, "    {},", line.join(",")).unwrap();
        }
        writeln!(out, "];").unwrap();
    };
    emit("ASCII_CLASSES", &mut classes[..128].iter().map(|&v| v as usize), 128);
    emit("BLOCK_INDEX", &mut stage1.iter().copied(), stage1.len());
    emit(
        "BLOCK_CLASSES",
        &mut blocks.iter().flat_map(|b| b.iter().map(|&v| v as usize)),
        blocks.len() * 256,
    );
    let target = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../src/unicode_classes.rs");
    fs::write(&target, out).unwrap();
    println!("wrote {} ({} unique blocks)", target.display(), blocks.len());
}
